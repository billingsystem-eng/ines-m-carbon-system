#!/usr/bin/env python3
"""Builds public/js/ph-regions.js (region map + NCR city map) from the faeldon/philippines-json-maps
GeoJSON (PSA/NAMRIA boundaries). Run:  python3 tools/build-regions.py <dir with country.json and mc-*.json>
Not needed at runtime; the generated file is committed."""
import json, math, glob, sys, os

SRC = sys.argv[1] if len(sys.argv) > 1 else 'geo'
OUT = os.path.join(os.path.dirname(__file__), '..', 'public', 'js', 'ph-regions.js')

def merc(lon, lat):
    return math.radians(lon), -math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))

def dp(pts, tol):
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1; L = math.hypot(dx, dy) or 1e-9
        best, bi = 0, -1
        for i in range(a + 1, b):
            d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / L
            if d > best: best, bi = d, i
        if best > tol: keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]

def rings_of(geom):
    polys = [geom['coordinates']] if geom['type'] == 'Polygon' else geom['coordinates']
    return [r for poly in polys for r in poly[:1]]  # outer rings only

def area_centroid(r):
    a = cx = cy = 0
    for i in range(len(r) - 1):
        x0, y0 = r[i]; x1, y1 = r[i + 1]; c = x0 * y1 - x1 * y0
        a += c; cx += (x0 + x1) * c; cy += (y0 + y1) * c
    if abs(a) < 1e-9: return r[0][0], r[0][1], 0
    return cx / (3 * a), cy / (3 * a), abs(a) / 2

def build(features, name_of, width, tol, minarea):
    rings_ll = [[rings_of(f['geometry'])] for f in features]
    xy = [[(merc(*p)) for p in r] for fr in rings_ll for rs in fr for r in rs]
    allp = [p for r in xy for p in r]
    x0, x1 = min(p[0] for p in allp), max(p[0] for p in allp)
    y0, y1 = min(p[1] for p in allp), max(p[1] for p in allp)
    pad = 0.04 * (x1 - x0)
    k = width / ((x1 - x0) + 2 * pad)
    W = width; H = ((y1 - y0) + 2 * pad) * k
    proj = lambda lon, lat: ((merc(lon, lat)[0] - x0 + pad) * k, (merc(lon, lat)[1] - y0 + pad) * k)
    out = []
    for f in features:
        d = []; best = (0, 0, 0)
        for r in rings_of(f['geometry']):
            pts = [proj(*p[:2]) for p in r]
            cx, cy, ar = area_centroid(pts)
            if ar < minarea and ar < best[2]: continue
            if ar > best[2]: best = (cx, cy, ar)
            # a ring starts and ends on the same point, so split it at the farthest vertex first
            m = max(range(len(pts)), key=lambda i: math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]))
            s = dp(pts[:m + 1], tol)[:-1] + dp(pts[m:], tol)
            if len(s) < 4 and ar < minarea * 4: continue
            d.append('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in s) + 'Z')
        out.append({'id': f['properties'].get('adm3_psgc') or f['properties']['adm1_psgc'], 'name': name_of(f['properties']),
                    'd': ''.join(d), 'cx': round(best[0], 1), 'cy': round(best[1], 1)})
    return {'w': round(W, 1), 'h': round(H, 1), 'k': k, 'x0': x0 - pad, 'y0': y0 - pad, 'items': out}

country = json.load(open(os.path.join(SRC, 'country.json')))
reg = build(country['features'], lambda p: p['adm1_en'], 560, 0.45, 2.0)
cities = []
for f in sorted(glob.glob(os.path.join(SRC, 'mc-*.json'))): cities += json.load(open(f))['features']
ncr = build(cities, lambda p: p['adm3_en'], 640, 0.12, 0.5)

def pack(m):  # projection constants let the page place a lat/lon on the same map
    return {'w': m['w'], 'h': m['h'], 'k': round(m['k'], 4), 'ox': round(m['x0'], 6), 'oy': round(m['y0'], 6), 'items': m['items']}
# Province maps for regions that open their own map in the live monitor (needs provdists-region-<id>.json in SRC)
out = {'country': pack(reg), 'ncr': pack(ncr)}
for key, rid in (('r4a', 400000000), ('r4b', 1700000000)):
    fp = os.path.join(SRC, f'provdists-region-{rid}.json')
    if not os.path.exists(fp): print('skipping', key, '- missing', fp); continue
    feats = json.load(open(fp))['features']
    for f in feats: f['properties']['adm3_psgc'] = f['properties']['adm2_psgc']  # province id, read by build()
    out[key] = pack(build(feats, lambda p: p['adm2_en'], 640, 0.12, 0.5))

js = '// Generated by tools/build-regions.py from PSA/NAMRIA boundaries (faeldon/philippines-json-maps). Do not edit by hand.\n'
js += 'window.PH_REGIONS = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n'
open(OUT, 'w', encoding='utf-8').write(js)
print(len(js), 'bytes;', len(reg['items']), 'regions;', len(ncr['items']), 'cities')
